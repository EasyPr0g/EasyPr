    function getAnswer(lesson, template) {
        const value = lesson[template.field];
        return Array.isArray(value) ? value[template.index || 0] : value;
    }

    function createQuestion(lessonIndex, questionIndex, courseLessons, lesson, template) {
        const answer = getAnswer(lesson, template);
        const preferredPool = [...new Set(courseLessons
            .map(otherLesson => getAnswer(otherLesson, template))
            .filter(value => typeof value === 'string' && value.trim() && value !== answer))];
        const fallbackPool = courseLessons.flatMap(otherLesson => [
            otherLesson.objective,
            otherLesson.challenge,
            ...(otherLesson.keyPoints || []),
            ...(otherLesson.practiceSteps || [])
        ]);
        const pool = [...new Set([...preferredPool, ...fallbackPool])]
            .filter(value => typeof value === 'string' && value.trim() && value !== answer);
        const distractors = [];
        const start = (lessonIndex * 7 + questionIndex * 11) % Math.max(pool.length, 1);
        for (let offset = 0; offset < pool.length && distractors.length < 3; offset++) {
            const option = pool[(start + offset) % pool.length];
            if (!distractors.includes(option)) distractors.push(option);
        }
        const options = [answer, ...distractors];
        const answerIndex = (lessonIndex + questionIndex * 3) % options.length;
        [options[0], options[answerIndex]] = [options[answerIndex], options[0]];
        return { prompt: template.prompt, options, answerIndex };
    }

